function digitId(d: number): SegmentId {
  return `s_${d}` as SegmentId;
}

/** Push the spoken form of a number: bearings digit by digit, 0–99 as words, larger digit by digit. */
function pushNumber(out: SpeechToken[], digits: string, digitWise: boolean): void {
  const n = Number(digits);
  if (digitWise || n > 99) {
    for (const c of digits) out.push(digitId(Number(c)));
    return;
  }
  if (n < 20) out.push(`s_${n}` as SegmentId);
  else {
    out.push(`s_${Math.floor(n / 10) * 10}` as SegmentId);
    if (n % 10) out.push(digitId(n % 10));
  }
}

/**
 * The subtitle spoken with AWACS segments (PAUSE at each comma / full stop). Words without a
 * segment are skipped. Returns the token list and how many subtitle words it covered.
 */
export function composeAwacs(text: string): { tokens: SpeechToken[]; covered: number; total: number } {
  const tokens: SpeechToken[] = [];
  let covered = 0;
  let total = 0;
  // phrases are split at punctuation that marks a pause
  // (multi-sentence segments are joined first so their phrase is matched whole)
  const chunks = text.replace(/turning back[!.,]\s*good work/gi, 'turning back good work').split(/[,.!?:;…—]+/);
  for (const chunk of chunks) {
    const w = speechWords(chunk);
    if (!w.length) continue;
    if (tokens.length && tokens[tokens.length - 1] !== PAUSE) tokens.push(PAUSE);
    total += w.length;
    let i = 0;
    while (i < w.length) {
      let matched = false;
      for (const [pw, id] of PHRASE_WORDS) {
        if (i + pw.length > w.length) continue;
        let ok = true;
        for (let j = 0; j < pw.length && ok; j++) ok = w[i + j] === pw[j];
        if (ok) {
          tokens.push(id);
          covered += pw.length;
          i += pw.length;
          matched = true;
          break;
        }
      }
      if (matched) continue;
      const word = w[i];
      if (/^\d+$/.test(word)) {
        const prev = i > 0 ? w[i - 1] : '';
        pushNumber(tokens, word, word.length === 3 && (prev === 'braa' || prev === 'bullseye'));
        covered++;
      } else if (WORDS[word]) {
        tokens.push(WORDS[word]);
        covered++;
      }
      i++;
    }
  }
  while (tokens.length && tokens[tokens.length - 1] === PAUSE) tokens.pop();
  return { tokens, covered, total };
}

/** Minimum share of the subtitle's words a composed call must speak (else: text-only call). */
const MIN_COVERAGE = 0.6;

/**
 * What to play for a radio call. `null` = text-only (click + static).
 * The returned array is new (radio calls are rare events, not per frame).
 */
export function resolveRadioSpeech(text: string | undefined, voice: VoiceId | undefined): SpeechToken[] | null {
  if (!voice) return null;
  if (!text) return [voice];
  if (clipMatchesText(voice, text)) return [voice];
  if (voice.startsWith('a_')) {
    const c = composeAwacs(text);
    if (c.tokens.length >= 2 && c.covered >= MIN_COVERAGE * c.total) return c.tokens;
  }
  return null;
}

/** Spoken words of a token list (for tests / logs). */
export function spokenText(tokens: readonly SpeechToken[], segmentText: (id: SegmentId) => string): string {
  const parts: string[] = [];
  for (const t of tokens) {
    if (t === PAUSE) continue;
    if ((VOICE_TEXT as Record<string, string>)[t]) parts.push(VOICE_TEXT[t as VoiceId]);
    else parts.push(segmentText(t as SegmentId));
  }
  return parts.join(' ');
}

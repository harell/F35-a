/** Lower-case words, punctuation stripped, a few brevity abbreviations expanded. */
export function speechWords(text: string): string[] {
  const t = text
    .toLowerCase()
    .replace(/\br\.\s*t\.\s*b\.?/g, 'rtb')
    .replace(/[^a-z0-9]+/g, ' ')
    .replace(/\brtb\b/g, 'return to base')
    .trim();
  return t ? t.split(' ') : [];
}

/** Do the words of `clip` appear, in order and adjacent, in `words`? */
function containsRun(words: readonly string[], clip: readonly string[]): boolean {
  if (!clip.length) return false;
  outer: for (let i = 0; i + clip.length <= words.length; i++) {
    for (let j = 0; j < clip.length; j++) if (words[i + j] !== clip[j]) continue outer;
    return true;
  }
  return false;
}

/** Does the fixed clip say exactly (a contiguous part of) what the subtitle says? */
export function clipMatchesText(id: VoiceId, text: string): boolean {
  return containsRun(speechWords(text), speechWords(VOICE_TEXT[id]));
}

